const langs: Record<string, Record<string, string>> = { ar, en };

export function t(key: string, vars?: Record<string, string | number>): string {
  if (!key) return "";
  const lang = (typeof localStorage !== "undefined" && localStorage.getItem("vireon:lang")) || "en";
  let str = (langs[lang] && langs[lang][key]) || (langs.en && langs.en[key]) || (langs.ar && langs.ar[key]) || key || "";
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      if (str && typeof str.replace === "function") {
        str = str.replace(`{${k}}`, String(v));
      }
    }
  }
  return str;
}

export function getLang(): "ar" | "en" {
  return ((typeof localStorage !== "undefined" && localStorage.getItem("vireon:lang")) || "en") as "ar" | "en";
}

export function isRTL(): boolean {
  return getLang() === "ar";
}

export function applyLangToDOM(lang?: "ar" | "en") {
  const l = lang || getLang();
  const root = document.documentElement;
  root.setAttribute("lang", l);
  root.setAttribute("dir", l === "ar" ? "rtl" : "ltr");
}

export function setLang(lang: "ar" | "en") {
  localStorage.setItem("vireon:lang", lang);
  applyLangToDOM(lang);
  window.location.reload();
}
